// The IBKR OAuth 1.0a variant, ported from IBind's Python
// implementation (ibind/oauth/oauth1a.py, Voyz/ibind — itself based on
// code provided by IBKR), cross-checked against IBKR's OAuth
// documentation. It differs from vanilla RFC 5849 in three ways:
//
//   - the live session token (LST) is derived from a Diffie-Hellman
//     exchange: the request to POST /oauth/live_session_token is
//     signed RSA-SHA256 with a base string prefixed by the "prepend" —
//     the hex of the RSA-decrypted access token secret;
//   - subsequent requests are signed HMAC-SHA256 keyed by the LST;
//   - signature values are percent-encoded inside the Authorization
//     header (IBind/IBKR behaviour, kept exactly).
//
// All functions here are pure so they can be tested against vectors
// generated by IBind's implementation (oauth1a_test.go).
package auth

import (
	"crypto"
	"crypto/hmac"
	"crypto/rand"
	"crypto/rsa"
	"crypto/sha1"
	"crypto/sha256"
	"crypto/x509"
	"encoding/base64"
	"encoding/hex"
	"encoding/pem"
	"fmt"
	"math/big"
	"net/url"
	"sort"
	"strings"
	"time"
)

// pctEncode percent-encodes like Python's urllib.parse.quote_plus:
// everything except [A-Za-z0-9_.-~] is escaped, space becomes '+'.
func pctEncode(s string) string {
	return url.QueryEscape(s)
}

// GenerateNonce returns a 16-character alphanumeric nonce (IBind
// uses secrets.choice over [A-Za-z0-9]).
func GenerateNonce() (string, error) {
	const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
	out := make([]byte, 16)
	rnd := make([]byte, 16)
	if _, err := rand.Read(rnd); err != nil {
		return "", err
	}
	for i, b := range rnd {
		out[i] = alphabet[int(b)%len(alphabet)]
	}
	return string(out), nil
}

// GenerateDHRandom returns a 256-bit random value as hex.
func GenerateDHRandom() (string, error) {
	max := new(big.Int).Lsh(big.NewInt(1), 256)
	n, err := rand.Int(rand.Reader, max)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("%x", n), nil
}

func hexToBig(h string) (*big.Int, error) {
	n, ok := new(big.Int).SetString(strings.TrimSpace(h), 16)
	if !ok {
		return nil, fmt.Errorf("invalid hex value")
	}
	return n, nil
}

// DHChallenge computes hex(g^random mod prime).
func DHChallenge(primeHex, randomHex string, generator int64) (string, error) {
	p, err := hexToBig(primeHex)
	if err != nil {
		return "", fmt.Errorf("dh prime: %w", err)
	}
	r, err := hexToBig(randomHex)
	if err != nil {
		return "", fmt.Errorf("dh random: %w", err)
	}
	ch := new(big.Int).Exp(big.NewInt(generator), r, p)
	return fmt.Sprintf("%x", ch), nil
}

// ParseRSAPrivateKey reads a PEM private key (PKCS#1 or PKCS#8).
func ParseRSAPrivateKey(pemData []byte) (*rsa.PrivateKey, error) {
	block, _ := pem.Decode(pemData)
	if block == nil {
		return nil, fmt.Errorf("no PEM block found")
	}
	if k, err := x509.ParsePKCS1PrivateKey(block.Bytes); err == nil {
		return k, nil
	}
	k, err := x509.ParsePKCS8PrivateKey(block.Bytes)
	if err != nil {
		return nil, fmt.Errorf("parsing private key: %w", err)
	}
	rk, ok := k.(*rsa.PrivateKey)
	if !ok {
		return nil, fmt.Errorf("private key is not RSA")
	}
	return rk, nil
}

// Prepend decrypts the base64 access token secret with the RSA
// encryption key (PKCS#1 v1.5) and returns the plaintext as hex.
func Prepend(accessTokenSecretB64 string, encKey *rsa.PrivateKey) (string, error) {
	ct, err := base64.StdEncoding.DecodeString(accessTokenSecretB64)
	if err != nil {
		return "", fmt.Errorf("decoding access token secret: %w", err)
	}
	pt, err := rsa.DecryptPKCS1v15(rand.Reader, encKey, ct)
	if err != nil {
		return "", fmt.Errorf("decrypting access token secret: %w", err)
	}
	return hex.EncodeToString(pt), nil
}

// BaseString builds the OAuth signature base string the IBKR way:
// METHOD & pct(url) & pct(sorted "k=v" pairs joined by '&'), with the
// prepend prefixed verbatim when non-empty (LST request only).
func BaseString(method, rawURL string, params map[string]string, prepend string) string {
	pairs := make([]string, 0, len(params))
	keys := make([]string, 0, len(params))
	for k := range params {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		pairs = append(pairs, k+"="+params[k])
	}
	joined := strings.Join(pairs, "&")
	base := method + "&" + pctEncode(rawURL) + "&" + pctEncode(joined)
	if prepend != "" {
		return prepend + base
	}
	return base
}

// RSASignSHA256 signs the base string with the RSA signature key
// (PKCS#1 v1.5, SHA-256) and returns the percent-encoded base64
// signature, as IBind puts it in the header.
func RSASignSHA256(baseString string, sigKey *rsa.PrivateKey) (string, error) {
	h := sha256.Sum256([]byte(baseString))
	sig, err := rsa.SignPKCS1v15(rand.Reader, sigKey, crypto.SHA256, h[:])
	if err != nil {
		return "", err
	}
	return pctEncode(base64.StdEncoding.EncodeToString(sig)), nil
}

// HMACSignSHA256 signs the base string with HMAC-SHA256 keyed by the
// base64-decoded live session token; percent-encoded like IBind.
func HMACSignSHA256(baseString, liveSessionToken string) (string, error) {
	key, err := base64.StdEncoding.DecodeString(liveSessionToken)
	if err != nil {
		return "", fmt.Errorf("decoding live session token: %w", err)
	}
	mac := hmac.New(sha256.New, key)
	mac.Write([]byte(baseString))
	return pctEncode(base64.StdEncoding.EncodeToString(mac.Sum(nil))), nil
}

// bigToByteArray renders a non-negative integer the way Java's
// BigInteger.toByteArray does (and IBind's to_byte_array): minimal
// big-endian bytes, prefixed with 0x00 when the bit length is a
// multiple of 8 so the value stays positive.
func bigToByteArray(x *big.Int) []byte {
	b := x.Bytes()
	if x.BitLen()%8 == 0 {
		return append([]byte{0}, b...)
	}
	return b
}

// ComputeLiveSessionToken derives the LST from the DH exchange:
// base64( HMAC-SHA1( key=byteArray(sharedSecret),
//
//	msg=bytes(hexDecode(prepend)) ) )
//
// where sharedSecret = dhResponse^dhRandom mod prime.
func ComputeLiveSessionToken(primeHex, randomHex, dhResponseHex, prepend string) (string, error) {
	p, err := hexToBig(primeHex)
	if err != nil {
		return "", fmt.Errorf("dh prime: %w", err)
	}
	r, err := hexToBig(randomHex)
	if err != nil {
		return "", fmt.Errorf("dh random: %w", err)
	}
	resp, err := hexToBig(dhResponseHex)
	if err != nil {
		return "", fmt.Errorf("dh response: %w", err)
	}
	shared := new(big.Int).Exp(resp, r, p)
	atsBytes, err := hex.DecodeString(prepend)
	if err != nil {
		return "", fmt.Errorf("prepend hex: %w", err)
	}
	mac := hmac.New(sha1.New, bigToByteArray(shared))
	mac.Write(atsBytes)
	return base64.StdEncoding.EncodeToString(mac.Sum(nil)), nil
}

// ValidateLiveSessionToken checks the LST against the signature IBKR
// returned: hex( HMAC-SHA1( key=base64Decode(lst), msg=consumerKey ) ).
func ValidateLiveSessionToken(lst, lstSignature, consumerKey string) bool {
	key, err := base64.StdEncoding.DecodeString(lst)
	if err != nil {
		return false
	}
	mac := hmac.New(sha1.New, key)
	mac.Write([]byte(consumerKey))
	return hex.EncodeToString(mac.Sum(nil)) == lstSignature
}

// AuthorizationHeader renders the OAuth Authorization header:
// OAuth realm="<realm>", k="v", ... with pairs sorted by key.
func AuthorizationHeader(realm string, params map[string]string) string {
	keys := make([]string, 0, len(params))
	for k := range params {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, 0, len(keys))
	for _, k := range keys {
		parts = append(parts, fmt.Sprintf("%s=\"%s\"", k, params[k]))
	}
	return fmt.Sprintf("OAuth realm=\"%s\", %s", realm, strings.Join(parts, ", "))
}

// OAuthParams assembles the standard OAuth header parameters for one
// request (without the signature).
func OAuthParams(consumerKey, accessToken, signatureMethod string) (map[string]string, error) {
	nonce, err := GenerateNonce()
	if err != nil {
		return nil, err
	}
	params := map[string]string{
		"oauth_consumer_key":     consumerKey,
		"oauth_nonce":            nonce,
		"oauth_signature_method": signatureMethod,
		"oauth_timestamp":        fmt.Sprintf("%d", time.Now().Unix()),
	}
	if accessToken != "" {
		params["oauth_token"] = accessToken
	}
	return params, nil
}
